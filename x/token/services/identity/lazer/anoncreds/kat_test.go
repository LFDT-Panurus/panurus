// katFixture is the decoded fixture of the known-answer test.
type katFixture struct {
	ipk, cred, state []byte
	attrs            [][]byte
	openings         map[uint32][]byte
}

func mustB64(tb testing.TB, s string) []byte {
	tb.Helper()
	b, err := base64.StdEncoding.DecodeString(s)
	require.NoError(tb, err)

	return b
}

func loadKATFixture(tb testing.TB) *katFixture {
	tb.Helper()

	return &katFixture{
		ipk:   mustB64(tb, katIpk),
		cred:  mustB64(tb, katCred),
		state: mustB64(tb, katState),
		attrs: [][]byte{
			mustB64(tb, katAttr0), mustB64(tb, katAttr1), mustB64(tb, katAttr2),
			mustB64(tb, katAttr3), mustB64(tb, katAttr4),
		},
		openings: map[uint32][]byte{0: mustB64(tb, katOpen0), 2: mustB64(tb, katOpen2), 3: mustB64(tb, katOpen3)},
	}
}

// TestKnownAnswerProofs generates a P2 presentation (nyms for attributes 0, 2
// and 3, nothing revealed) and a signature of knowledge from fixed inputs and
// fixed prover coins, checks that both verify and pins their SHA-256 (see
// katPresDigest). Proofs are deterministic in their inputs and coins, so a
// digest mismatch means that the transcript changed.
func TestKnownAnswerProofs(t *testing.T) {
	f := loadKATFixture(t)
	u, err := NewUser(f.ipk)
	require.NoError(t, err)
	t.Cleanup(u.Clear)
	require.NoError(t, u.Import(f.state, f.attrs))
	require.NoError(t, u.CredVerify(f.cred))

	idxCom := []uint32{0, 2, 3}
	coms := make([]*Commitment, 0, len(idxCom))
	nyms := make([][]byte, 0, len(idxCom))
	for _, i := range idxCom {
		c, err := CommitWithOpening(f.attrs[i], f.openings[i])
		require.NoError(t, err)
		t.Cleanup(c.Clear)
		coms = append(coms, c)
		nyms = append(nyms, c.Nym)
	}

	pres, err := u.presGenCoins(f.cred, coms, idxCom, katCtx, katCoins, true)
	require.NoError(t, err)
	v, err := NewVerifier(f.ipk)
	require.NoError(t, err)
	t.Cleanup(v.Clear)
	require.NoError(t, v.PresVer(revealed(f.attrs, nil), nil, nyms, idxCom, pres, katCtx))

	sok, err := coms[0].sokProveCoins(katCtx, f.attrs[0], katCoins, true)
	require.NoError(t, err)
	require.NoError(t, SokVerify(coms[0].Nym, katCtx, sok))

	presDigest, sokDigest := sha256.Sum256(pres), sha256.Sum256(sok)
	assert.Equal(t, katPresDigest, hex.EncodeToString(presDigest[:]), "presentation transcript changed (%d bytes)", len(pres))
	assert.Equal(t, katSokDigest, hex.EncodeToString(sokDigest[:]), "signature of knowledge transcript changed (%d bytes)", len(sok))
}
